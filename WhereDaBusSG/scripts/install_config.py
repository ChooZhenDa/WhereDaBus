"""Create an isolated, persistent Docker installation without adopting old data.

Invoked inside Docker by the Windows launcher. Credentials never cross shell
arguments or launcher metadata. Only the LTA AccountKey is entered by the user.
"""
import argparse
import getpass
import os
from pathlib import Path
import re
import secrets
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
if __package__ in (None, ''):
    sys.path.insert(0, str(ROOT))
from scripts.configure import KEY_PATTERN, read_config, validate_config

PROJECT_PATTERN = re.compile(r'wheredabus-[0-9a-f]{16}')


def validate_installation(values):
    if not PROJECT_PATTERN.fullmatch(values.get('WDB_PROJECT', '')):
        raise ValueError('This folder does not have its own standalone installation. Run Setup.cmd.')
    validate_config(values)
    return values


def read_selected_port(root):
    path = root / '.launcher-port'
    try:
        port = path.read_text(encoding='ascii').strip()
    except (OSError, UnicodeError):
        raise ValueError('A free application port was not selected. Run Setup.cmd again.') from None
    if not re.fullmatch(r'[0-9]{1,5}', port) or not 1024 <= int(port) <= 65535:
        raise ValueError('The application port selection is invalid. Run Setup.cmd again.')
    return port


def current_bytes(path):
    if path.is_symlink():
        raise ValueError('.env must be a regular file in this project folder.')
    if not path.exists():
        return None
    if not path.is_file():
        raise ValueError('.env must be a regular file in this project folder.')
    return path.read_bytes()


def atomic_private_write(root, content, original):
    """Back up an existing file and replace it only after complete validation."""
    path = root / '.env'
    if current_bytes(path) != original:
        raise ValueError('Configuration changed while Setup was open. Close other setup windows and retry.')
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode='wb', prefix='.env.install-', dir=root, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        if original is not None:
            backup = root / ('.env.before-standalone-' + secrets.token_hex(12))
            descriptor = os.open(backup, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(descriptor, 'wb') as stream:
                stream.write(original)
                stream.flush()
                os.fsync(stream.fileno())
        if current_bytes(path) != original:
            raise ValueError('Configuration changed while Setup was open. Close other setup windows and retry.')
        os.replace(temporary, path)
        temporary = None
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def setup_installation(root, prompt=getpass.getpass):
    root = Path(root)
    path = root / '.env'
    original = current_bytes(path)
    values = None
    if original is not None:
        try:
            values = validate_installation(read_config(path))
        except (ValueError, UnicodeError):
            values = None
    fresh = values is None
    if fresh:
        port = read_selected_port(root)
        values = {
            'WDB_PROJECT': 'wheredabus-' + secrets.token_hex(8),
            'POSTGRES_PASSWORD': secrets.token_hex(24),
            'MONGO_PASSWORD': secrets.token_hex(24),
            'LTA_ACCOUNT_KEY': '',
            'APP_PORT': port,
            'SAMPLE_STOPS': '',
            'SAMPLE_SERVICES': '',
        }
        print('Creating your own installation with new databases and generated passwords.')
        if original is not None:
            print('The previous configuration will be kept in a private backup. Existing databases are retained separately.')
        print('Paste your LTA DataMall AccountKey below. It will not be displayed.')
        print('Press Enter to start in demo mode instead.')
        key = prompt('LTA AccountKey: ').strip()
    else:
        print('Keeping this installation and its database passwords.')
        if values.get('LTA_ACCOUNT_KEY'):
            key = prompt('New LTA AccountKey (Enter to keep current): ').strip()
        else:
            print('Paste your LTA DataMall AccountKey, or press Enter to keep demo mode.')
            key = prompt('LTA AccountKey: ').strip()
    if key and not KEY_PATTERN.fullmatch(key):
        raise ValueError('The AccountKey contains unsupported characters. Run Setup.cmd and paste it without spaces or quotes.')
    if key:
        values['LTA_ACCOUNT_KEY'] = key
    validate_installation(values)
    if fresh:
        text = '# Private settings generated by Setup.cmd. Keep this file with this installation.\n'
        text += '\n'.join(name + '=' + value for name, value in values.items()) + '\n'
        atomic_private_write(root, text.encode('utf-8'), original)
    elif key:
        # Keep the user's comments and unrelated settings when only the key changes.
        lines = original.decode('utf-8-sig').splitlines()
        found = False
        for index, line in enumerate(lines):
            if re.match(r'\s*LTA_ACCOUNT_KEY\s*=', line):
                lines[index] = 'LTA_ACCOUNT_KEY=' + key
                found = True
        if not found:
            lines.append('LTA_ACCOUNT_KEY=' + key)
        updated = ('\n'.join(lines) + '\n').encode('utf-8')
        if updated != original:
            atomic_private_write(root, updated, original)
    if validate_installation(read_config(path)) != values:
        raise ValueError('Configuration changed while Setup was open. Close other setup windows and retry.')
    return values


def check_installation(root):
    try:
        return validate_installation(read_config(Path(root) / '.env'))
    except (ValueError, OSError, UnicodeError):
        raise ValueError('This folder is not configured for standalone use. Run Setup.cmd to create a separate installation.') from None


def write_launcher_state(root, values):
    validate_installation(values)
    text = ('LAUNCH_PROJECT=' + values['WDB_PROJECT'] + '\n'
            'LAUNCH_PORT=' + values['APP_PORT'] + '\n'
            'LAUNCH_HAS_KEY=' + str(int(bool(values.get('LTA_ACCOUNT_KEY')))) + '\n')
    path = Path(root) / '.launcher-state'
    temporary = Path(root) / ('.launcher-state-' + secrets.token_hex(8))
    try:
        # Windows FINDSTR /X requires CRLF even when this helper runs in Linux
        # Docker. Never depend on the host's default text newline translation.
        with temporary.open('x', encoding='ascii', newline='\r\n') as stream:
            stream.write(text)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument('action', choices=('setup', 'check'))
    args = parser.parse_args(argv)
    try:
        values = setup_installation(ROOT) if args.action == 'setup' else check_installation(ROOT)
        write_launcher_state(ROOT, values)
        print('Configuration ready.')
        return 0
    except (EOFError, KeyboardInterrupt):
        print('\nSetup cancelled. Run Setup.cmd when ready.', file=sys.stderr)
        return 1
    except (ValueError, OSError) as error:
        print('Configuration stopped: ' + str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
